class AccountAccount(models.Model):
    _inherit = 'account.account'

    @api.model
    def _cn_apply_standard_account_names(self):
        """把科目编码命中中国企业会计准则科目表的科目，名称强制改为与用友、
        金蝶一致的标准中文名称，直接写入 name 字段本身，不依赖 Odoo 翻译层
        是否已加载/激活对应语言。按编码匹配，不区分公司/国家，避免依赖较
        脆弱的跨表字段（account_fiscal_country_id）做过滤。"""
        accounts = self.search([('code', 'in', list(CN_ACCOUNT_NAME_MAP))])
        for account in accounts:
            name = CN_ACCOUNT_NAME_MAP.get(account.code)
            if name and account.name != name:
                account.name = name
